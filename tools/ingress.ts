import { services, zones } from "@micro/routing";

type IngressPath = {
  path: string;
  service: string;
  comment?: string;
};

/**
 * Generates the production routing contract from the same registry the local
 * proxy uses. The manifests are a reference for the platform team; the PoC
 * demo runs locally.
 */
export function renderIngress({
  namespace = "relay",
  host = "relay.example.com",
  ingressClass = "nginx",
}: {
  namespace?: string;
  host?: string;
  ingressClass?: string;
} = {}): string {
  const paths: IngressPath[] = [];

  for (const zone of zones) {
    if (zone.path !== "/") {
      paths.push({
        path: zone.path,
        service: `relay-${zone.id}`,
        comment: `${zone.team} zone`,
      });
    }
    if (zone.assets) {
      paths.push({
        path: zone.assets,
        service: `relay-${zone.id}`,
        comment: "immutable build output",
      });
    }
  }

  for (const service of services) {
    paths.push({ path: service.path, service: `relay-${service.id}` });
  }

  paths.push({ path: "/", service: "relay-shell", comment: "shell catches the rest" });

  const rules = paths
    .map(
      (entry) => `          # ${entry.comment ?? entry.service}
          - path: ${entry.path}
            pathType: Prefix
            backend:
              service:
                name: ${entry.service}
                port:
                  number: 80`,
    )
    .join("\n");

  return `# Generated by pnpm gen:ingress from packages/routing/src/zones.ts
# Do not edit by hand. PathType Prefix is segment-aware in Kubernetes, so
# /ops matches /ops and /ops/x but not /opsx.
apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: relay
  namespace: ${namespace}
  annotations:
    # Identity is enforced at the cluster edge, not by the shell. Replace these
    # with the platform's forward-auth or oauth2-proxy configuration.
    # nginx.ingress.kubernetes.io/auth-url: "https://sso.example.com/oauth2/auth"
    # nginx.ingress.kubernetes.io/auth-signin: "https://sso.example.com/oauth2/start?rd=$scheme://$host$request_uri"
    nginx.ingress.kubernetes.io/proxy-body-size: "2m"
spec:
  ingressClassName: ${ingressClass}
  rules:
    - host: ${host}
      http:
        paths:
${rules}
  # tls:
  #   - hosts: ["${host}"]
  #     secretName: relay-tls
`;
}
